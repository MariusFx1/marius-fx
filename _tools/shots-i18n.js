const puppeteer = require('puppeteer-core');
const BASE = process.env.BASE || 'https://mariusfx1.github.io/marius-fx', OUT = '/workspace/shots/i18n';
const L = process.argv[2] || 'en';
require('fs').mkdirSync(OUT, { recursive: true });
const sleep = ms => new Promise(r => setTimeout(r, ms));
(async () => {
  const b = await puppeteer.launch({ executablePath: '/usr/bin/google-chrome', headless: 'new', args: ['--no-sandbox'] });
  const p = await b.newPage();
  const pre = L === 'ro' ? '' : L + '/';
  await p.setViewport({ width: 1280, height: 860 });
  await p.goto(`${BASE}/${pre}index.html`, { waitUntil: 'networkidle2' }); await sleep(1500);
  await p.screenshot({ path: `${OUT}/${L}-home-desktop.png` });
  await p.evaluate(() => document.querySelector('.lang-btn').click()); await sleep(300);
  await p.screenshot({ path: `${OUT}/${L}-home-desktop-switcher.png` });
  await p.goto(`${BASE}/${pre}lectie.html#cap-3`, { waitUntil: 'networkidle2' }); await sleep(1200);
  await p.screenshot({ path: `${OUT}/${L}-lesson-desktop.png` });
  await p.goto(`${BASE}/${pre}simulator.html`, { waitUntil: 'networkidle2' }); await sleep(800);
  await p.screenshot({ path: `${OUT}/${L}-simulator-setup-desktop.png` });
  await p.evaluate(() => { localStorage.setItem('mfx-sim-help-seen', '1'); document.getElementById('sim-start').click(); });
  await p.waitForFunction(() => window.__sim && window.__sim.S && window.__sim.S.view, { timeout: 20000 }).catch(() => {});
  await sleep(800); await p.evaluate(() => { const h = document.getElementById('sim-help'); if (h && h.open) h.close(); document.getElementById('sim-place').click(); }); await sleep(600);
  await p.screenshot({ path: `${OUT}/${L}-simulator-workspace-desktop.png` });
  const m = await b.newPage();
  await m.setViewport({ width: 390, height: 844, deviceScaleFactor: 2, isMobile: true, hasTouch: true });
  await m.goto(`${BASE}/${pre}index.html`, { waitUntil: 'networkidle2' }); await sleep(1200);
  await m.screenshot({ path: `${OUT}/${L}-home-mobile.png` });
  await m.click('.menu-toggle'); await sleep(400);
  await m.evaluate(() => document.querySelector('.lang-btn').click()); await sleep(300);
  await m.screenshot({ path: `${OUT}/${L}-home-mobile-switcher-open.png` });
  await m.goto(`${BASE}/${pre}lectie.html`, { waitUntil: 'networkidle2' }); await sleep(800);
  await m.screenshot({ path: `${OUT}/${L}-lesson-mobile.png` });
  await m.goto(`${BASE}/${pre}simulator.html`, { waitUntil: 'networkidle2' }); await sleep(600);
  await m.evaluate(() => { localStorage.setItem('mfx-sim-help-seen', '1'); document.getElementById('sim-start').click(); });
  await m.waitForFunction(() => window.__sim && window.__sim.S && window.__sim.S.view, { timeout: 20000 }).catch(() => {});
  await sleep(800); await m.evaluate(() => { const h = document.getElementById('sim-help'); if (h && h.open) h.close(); });
  await m.screenshot({ path: `${OUT}/${L}-simulator-mobile.png` });
  await b.close(); console.log('shots ok');
})();
